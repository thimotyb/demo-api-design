"""Pydantic models: identical to the synchronous version (orders_api/app/models.py).

Models describe data, not how a request is processed, so async changes nothing here.

A Pydantic model describes a JSON object. FastAPI uses these classes to
  * validate incoming request bodies,
  * serialize outgoing responses,
  * generate the JSON Schema shown in /docs and /openapi.json.
"""

from datetime import date

from pydantic import BaseModel, ConfigDict, Field


# ---------------------------------------------------------------------------
# Input models: what the client sends
# ---------------------------------------------------------------------------

class OrderLineIn(BaseModel):
    """One line of an order, as sent by the client."""

    # Field(...) adds constraints. FastAPI answers 422 if a constraint fails.
    sku: str = Field(min_length=1)
    description: str = ""                 # a default value makes the field optional
    quantity: int = Field(ge=1)           # ge = "greater than or equal to"
    unit_price: float = Field(ge=0)


class OrderCreate(BaseModel):
    """Body of POST /orders (and PUT /orders/{id}, which replaces the whole order)."""

    # populate_by_name lets the client use either "order_date" or the alias "orderDate".
    model_config = ConfigDict(populate_by_name=True)

    customer: str = Field(min_length=1)
    # alias: the JSON name is "orderDate", the Python name is order_date.
    # default_factory runs when the field is missing, so the default is "today".
    order_date: date = Field(default_factory=date.today, alias="orderDate")
    status: str = "new"
    lines: list[OrderLineIn] = []


class OrderPatch(BaseModel):
    """Body of PATCH /orders/{id}: every field is optional, only the sent ones change."""

    customer: str | None = None
    status: str | None = None


# ---------------------------------------------------------------------------
# Output models: what the API returns
# ---------------------------------------------------------------------------

class OrderLine(OrderLineIn):
    """A stored line: the input fields plus an id generated by the server."""

    id: int


class OrderSummary(BaseModel):
    """Short view of an order, used by the list endpoint (no lines)."""

    model_config = ConfigDict(populate_by_name=True)

    id: int
    customer: str
    order_date: date = Field(alias="orderDate")
    status: str
    line_count: int
    total_amount: float


class OrderDetail(OrderSummary):
    """Full view of an order: the summary plus its lines."""

    lines: list[OrderLine]
