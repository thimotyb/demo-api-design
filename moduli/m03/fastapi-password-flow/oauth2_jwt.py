"""Step 4 - OAuth2 with password hashing and Bearer with JWT tokens.

Run:  uvicorn oauth2_jwt:app --reload
Then in /docs press Authorize and log in as johndoe / secret.

The tutorial this follows: https://fastapi.tiangolo.com/tutorial/security/oauth2-jwt/

This step removes the two teaching limits of step 3:
- passwords are stored as Argon2 hashes and checked with pwdlib;
- the access token is a signed JWT with an expiry, so it cannot be forged without the key.

Still not production code: the secret key is a demo default, users are in memory, and there
is no refresh token, revocation or rate limiting.
"""
import os
from datetime import datetime, timedelta, timezone
from typing import Annotated

import jwt
from fastapi import Depends, FastAPI, HTTPException, status
from fastapi.security import OAuth2PasswordBearer, OAuth2PasswordRequestForm
from jwt.exceptions import InvalidTokenError
from pwdlib import PasswordHash
from pydantic import BaseModel

